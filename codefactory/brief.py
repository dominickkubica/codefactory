"""Text views of the graph for AI coding agents (Claude Code) and terminals: a whole-repo brief, and the context of one
file or function before changing it. Markdown, with `file:line` references, kept short enough to read in one go."""
from __future__ import annotations

import re
from collections import Counter, defaultdict, deque

TESTS = ("tests", "test", "__tests__", "__mocks__")


def is_test(path: str) -> bool:
    parts = path.split("/")
    return any(p in TESTS for p in parts[:-1]) or parts[-1].startswith("test_") or ".test." in parts[-1] \
        or ".spec." in parts[-1]


class View:
    """Indexes over a graph dict (from build(...).to_dict() or a saved .json)."""

    def __init__(self, g: dict):
        self.g = g
        self.fn = {f["id"]: f for f in g["functions"]}
        self.file = {f["id"]: f for f in g["files"]}
        self.callers = defaultdict(list)
        self.callees = defaultdict(list)
        self.refs_in = defaultdict(list)
        self.importers = defaultdict(set)
        self.imports = defaultdict(set)
        for e in g["edges"]:
            if e["kind"] == "call":
                self.callers[e["dst"]].append(e)
                self.callees[e["src"]].append(e)
            elif e["kind"] == "ref":
                self.refs_in[e["dst"]].append(e)
            else:
                self.importers[e["dst"]].add(e["src"])
                self.imports[e["src"]].add(e["dst"])
        self.flags_on = defaultdict(list)
        for fl in g["flags"]:
            self.flags_on[fl["target"]].append(fl)
        self.fns_in = defaultdict(list)
        for f in g["functions"]:
            if f["kind"] != "module":
                self.fns_in[f["file"]].append(f)

    def where(self, fid: str) -> str:
        f = self.fn.get(fid)
        return f"{f['file']}:{f['line']}" if f else fid

    def label(self, fid: str) -> str:
        f = self.fn.get(fid)
        if not f:
            return fid
        return f"top-level code in {f['file']}" if f["kind"] == "module" else f"{f['qualname']}"

    def dependents(self, start: list[str]) -> set[str]:
        """Everything that calls these, directly or through others (who could break if they change)."""
        seen, q = set(start), deque(start)
        while q:
            cur = q.popleft()
            for e in self.callers[cur] + self.refs_in[cur]:
                if e["src"] not in seen:
                    seen.add(e["src"])
                    q.append(e["src"])
        return seen - set(start)


ADVICE = re.compile(r"^(.*?(?:loop \(line[^)]*\)(?:, and that reaches [^:]+\(\))?|loop \(line \d+\)))[:.].*$", re.S)


def _flag_line(v: View, fl: dict) -> str:
    """One issue on one line. For loop checks the advice is said once in the section's note, not on every line."""
    target = fl["target"]
    if target in v.fn:
        f = v.fn[target]
        loc = f"{f['file']}:{fl.get('line') or f['line']}"
    else:
        loc = target
    msg = fl["message"]
    if fl["kind"] in ("io_in_loop", "quadratic_scan", "sequential_await"):
        m = ADVICE.match(msg)
        msg = m.group(1) if m else msg
    return f"- `{loc}` {msg}"


def brief_markdown(g: dict, limit: int = 12) -> str:
    v = View(g)
    name = g["root"].replace("\\", "/").rstrip("/").split("/")[-1]
    code_files = [f for f in g["files"] if not is_test(f["id"])]
    fns = [f for f in g["functions"] if f["kind"] != "module"]
    lines = [f"# Code map: {name}",
             f"{g['language']} · {len(g['files'])} files ({len(g['files']) - len(code_files)} tests) · {len(fns)} functions · "
             f"{sum(f['loc'] for f in g['files']):,} lines. Generated by codefactory (static analysis: calls through "
             "dynamic dispatch may be missing). `file:line` points at code.", ""]

    # layers and how they depend on each other
    layer_of = {f["id"]: f["layer"] for f in g["files"]}
    fn_file = {f["id"]: f["file"] for f in g["functions"]}
    deps: dict[str, Counter] = defaultdict(Counter)
    for e in g["edges"]:
        if e["kind"] == "call":
            a, b = layer_of.get(fn_file.get(e["src"])), layer_of.get(fn_file.get(e["dst"]))
            if a and b and a != b:
                deps[a][b] += e["count"]
    sev_by_layer: dict[str, Counter] = defaultdict(Counter)
    for fl in g["flags"]:
        file = fn_file.get(fl["target"], fl["target"])
        sev_by_layer[layer_of.get(file, "?")][fl["severity"]] += 1
    lines += ["## Layers (left to right: uses others → used by others)", "",
              "| Layer | Files | Lines | Calls into | Issues (high/warn/info) |", "|---|---|---|---|---|"]
    for layer in g["layers"]:
        members = [f for f in g["files"] if f["layer"] == layer]
        into = ", ".join(f"{k} ({n})" for k, n in deps[layer].most_common(4)) or "-"
        s = sev_by_layer[layer]
        lines.append(f"| {layer} | {len(members)} | {sum(f['loc'] for f in members):,} | {into} | "
                     f"{s['high']}/{s['warn']}/{s['info']} |")
    if g.get("rules"):
        lines += ["", "Forbidden layer imports (factory.toml): " + ", ".join(g["rules"])]

    # most-used code
    caller_files = {fid: {fn_file.get(e["src"]) for e in v.callers[fid]} - {f["file"]} for fid, f in v.fn.items()}
    top = sorted((f for f in fns if not is_test(f["file"])), key=lambda f: -len(caller_files[f["id"]]))[:8]
    lines += ["", "## Most-used code (a change here ripples; check callers first)", ""]
    lines += [f"- `{f['file']}:{f['line']}` {f['qualname']}: called from {len(caller_files[f['id']])} files"
              for f in top if caller_files[f["id"]]]

    # issues, grouped by what to do about them
    by_kind: dict[str, list] = defaultdict(list)
    for fl in g["flags"]:
        by_kind[fl["kind"]].append(fl)

    def section(title: str, kinds: list[str], note: str = "") -> None:
        items = [fl for k in kinds for fl in by_kind.get(k, [])]
        items = [fl for fl in items if not is_test(fn_file.get(fl["target"], fl["target"]))] or items
        if not items:
            return
        items.sort(key=lambda fl: ({"high": 0, "warn": 1, "info": 2}[fl["severity"]], fl["target"]))
        lines.extend(["", f"## {title} ({len(items)})"] + ([note] if note else []) + [""])
        lines.extend(_flag_line(v, fl) for fl in items[:limit])
        if len(items) > limit:
            lines.append(f"- … {len(items) - limit} more: `codefactory flags --json` lists all")

    section("Import loops and layer violations", ["cycle", "layer_violation"])
    section("Database, file or network calls inside loops", ["io_in_loop"],
            "Reads and network calls first (the N+1 pattern: replace with one batched query, WHERE id IN (…) or a JOIN, "
            "or one request); then writes and files (usually fine inside one transaction; batch them if there are many).")
    # duplicates as clusters, with what merging would save
    clusters = []
    seen = set()
    for fl in by_kind.get("duplicate", []) + by_kind.get("similar", []):
        group = frozenset([fl["target"], *fl.get("related", [])])
        if group in seen:
            continue
        seen.add(group)
        members = [v.fn[i] for i in group if i in v.fn]
        if len(members) < 2:
            continue
        saved = sum(m["loc"] for m in members) - max(m["loc"] for m in members)
        pct = "same" if fl["kind"] == "duplicate" else f"{round(fl.get('score', 0.8) * 100)}% similar"
        clusters.append((saved, pct, members))
    if clusters:
        clusters.sort(key=lambda c: -c[0])
        lines += ["", f"## Copied code ({len(clusters)} groups; merging each into one function saves the lines shown)", ""]
        for saved, pct, members in clusters[:limit]:
            lines.append(f"- {pct}, ~{saved} lines: " + " · ".join(f"`{m['file']}:{m['line']}` {m['qualname']}" for m in members))
    section("Searches inside loops", ["quadratic_scan"], "Fine for short lists; for long ones build a Map or Set once "
            "before the loop.")
    section("Awaits inside loops", ["sequential_await"], "Each round waits for the last; if they're independent, run "
            "them together (Promise.all / asyncio.gather). Not for writes that must stay in order.")
    section("Unused code (verify before deleting: frameworks may call it by name)", ["unused"])
    section("Only called from tests", ["test_only"])
    longest = sorted((f for f in fns if not is_test(f["file"])), key=lambda f: -f["loc"])[:limit]
    if longest:
        lines += ["", "## Longest functions", ""]
        lines += [f"- `{f['file']}:{f['line']}` {f['qualname']}: {f['loc']} lines" for f in longest]
    lines += ["", "## Next", "",
              "- Before changing a function or file: `codefactory context <name|file>` (callers, impact, tests to run).",
              "- What it eventually calls: `codefactory trace <function>`; how A reaches B: `codefactory path A B`.",
              "- Anything else: `codefactory query \"SELECT …\"` (tables files, functions, edges, flags; views function_stats, file_deps)."]
    return "\n".join(lines) + "\n"


def resolve_target(g: dict, query: str) -> tuple[str, list[dict]]:
    """("file", [file]) or ("function", [fn]) for a path or a name; several matches -> all of them."""
    q = query.replace("\\", "/").lstrip("./")
    files = [f for f in g["files"] if f["id"] == q] or [f for f in g["files"] if f["id"].endswith("/" + q) or f["id"].endswith(q)]
    if files and ("/" in q or "." in q.split("/")[-1]):
        return "file", files
    fns = [f for f in g["functions"] if f["kind"] != "module"]
    for key in ("id", "qualname", "name"):
        hits = [f for f in fns if f[key] == query]
        if hits:
            return "function", hits
    hits = [f for f in fns if f["id"].endswith(query)]
    if hits:
        return "function", hits
    return ("file", files) if files else ("none", [])


def context_data(g: dict, query: str, limit: int = 20) -> dict:
    v = View(g)
    kind, hits = resolve_target(g, query)
    if kind == "none":
        return {"error": f"no file or function matches {query!r}"}
    if len(hits) > 1:
        return {"error": f"{query!r} matches {len(hits)} {kind}s; use one of these", "matches": [h["id"] for h in hits[:30]]}
    t = hits[0]
    if kind == "function":
        ids = [t["id"]]
        callers = sorted({e["src"] for e in v.callers[t["id"]]})
        callees = sorted({e["dst"] for e in v.callees[t["id"]]})
        refs = sorted({e["src"] for e in v.refs_in[t["id"]]} - set(callers))
        base = {"kind": "function", "id": t["id"], "file": t["file"], "line": t["line"], "end": t["end"], "loc": t["loc"],
                "layer": v.file.get(t["file"], {}).get("layer"), "io": t.get("io", []),
                "callers": [{"id": c, "at": v.where(c)} for c in callers[:limit]], "callers_total": len(callers),
                "referenced_by": [{"id": c, "at": v.where(c)} for c in refs[:limit]],
                "calls": [{"id": c, "at": v.where(c)} for c in callees[:limit]], "calls_total": len(callees)}
    else:
        ids = [f["id"] for f in v.fns_in[t["id"]]] + [f"{t['id']}::<module>"]
        base = {"kind": "file", "id": t["id"], "loc": t["loc"], "layer": t["layer"],
                "functions": [{"name": f["qualname"], "line": f["line"], "loc": f["loc"],
                               "callers": len(v.callers[f["id"]]), "calls": len(v.callees[f["id"]]),
                               "issues": [fl["kind"] for fl in v.flags_on[f["id"]]]} for f in sorted(v.fns_in[t["id"]], key=lambda f: f["line"])],
                "imported_by": sorted(v.importers[t["id"]])[:limit], "imported_by_total": len(v.importers[t["id"]]),
                "imports": sorted(v.imports[t["id"]])[:limit]}
    dependents = v.dependents(ids)
    dep_files = {v.fn[d]["file"] for d in dependents if d in v.fn}
    base["impact"] = {"functions": len(dependents), "files": len(dep_files),
                      "layers": sorted({v.file[f]["layer"] for f in dep_files if f in v.file})}
    base["tests"] = sorted(f for f in dep_files | set(v.importers.get(t.get("file", t["id"]), set())) if is_test(f))[:limit]
    issues = [fl for i in dict.fromkeys(ids + [t["id"]]) for fl in v.flags_on.get(i, [])]
    base["issues"] = [{"kind": fl["kind"], "severity": fl["severity"], "at": f"{v.fn[fl['target']]['file']}:{fl.get('line') or v.fn[fl['target']]['line']}"
                       if fl["target"] in v.fn else fl["target"], "message": fl["message"],
                       "related": [v.where(r) for r in fl.get("related", [])]} for fl in issues]
    return base


def context_markdown(g: dict, query: str, limit: int = 20) -> str:
    c = context_data(g, query, limit)
    if "error" in c:
        return c["error"] + ("\n" + "\n".join(f"- {m}" for m in c.get("matches", [])) if c.get("matches") else "") + "\n"
    out = []
    if c["kind"] == "function":
        out += [f"# {c['id'].split('::')[1]}  (`{c['file']}:{c['line']}`–{c['end']}, {c['loc']} lines, layer {c['layer']})", ""]
        if c["io"]:
            out.append(f"Does I/O itself: {', '.join(c['io'])}")
        out += ["", f"## Called by ({c['callers_total']})"] + [f"- `{x['at']}` {x['id'].split('::')[1]}" for x in c["callers"]]
        if c["referenced_by"]:
            out += ["", "## Passed around by (callbacks, returned from hooks)"] + [f"- `{x['at']}` {x['id'].split('::')[1]}" for x in c["referenced_by"]]
        out += ["", f"## Calls ({c['calls_total']})"] + [f"- `{x['at']}` {x['id'].split('::')[1]}" for x in c["calls"]]
    else:
        out += [f"# {c['id']}  ({c['loc']} lines, layer {c['layer']})", "", "## Functions", "",
                "| Function | Line | Lines | Callers | Calls | Issues |", "|---|---|---|---|---|---|"]
        out += [f"| {f['name']} | {f['line']} | {f['loc']} | {f['callers']} | {f['calls']} | {', '.join(f['issues']) or '-'} |"
                for f in c["functions"]]
        out += ["", f"## Imported by ({c['imported_by_total']})"] + [f"- {x}" for x in c["imported_by"]]
        out += ["", "## Imports"] + [f"- {x}" for x in c["imports"]]
    imp = c["impact"]
    out += ["", "## Impact of changing it",
            f"{imp['functions']} functions in {imp['files']} files depend on it, directly or not"
            + (f" (layers: {', '.join(imp['layers'])})." if imp["layers"] else ".")]
    if c["tests"]:
        out += ["", "## Tests that exercise it (run these after a change)"] + [f"- {t}" for t in c["tests"]]
    if c["issues"]:
        out += ["", "## Issues"] + [f"- `{i['at']}` {i['kind']} ({i['severity']}): {i['message']}" for i in c["issues"]]
    return "\n".join(out) + "\n"
